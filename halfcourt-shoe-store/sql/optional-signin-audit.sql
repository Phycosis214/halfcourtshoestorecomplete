-- Optional, additive schema for customer sign-in monitoring.
-- This does not seed fake history and does not change existing customer rows.
-- Apply after the base schema. api.php records successful customer logins here.

CREATE TABLE IF NOT EXISTS customer_sign_in_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  signed_in_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_customer_sign_in_events_signed_in_at
  ON customer_sign_in_events (signed_in_at DESC);

CREATE INDEX IF NOT EXISTS idx_customer_sign_in_events_customer
  ON customer_sign_in_events (customer_id, signed_in_at DESC);

ALTER TABLE customer_sign_in_events ENABLE ROW LEVEL SECURITY;
